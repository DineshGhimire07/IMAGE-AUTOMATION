"""Configurable resilient selectors and page state detection for ChatGPT."""
from __future__ import annotations

from dataclasses import dataclass
from typing import List


@dataclass
class ChatGPTSelectors:
    """
    Resilient selectors prioritizing accessible roles, ARIA labels, 
    and observable UI attributes over brittle obfuscated CSS classes.
    """
    # Main prompt input textarea / contenteditable div
    prompt_input: List[str] = (
        "#prompt-textarea",
        "div[id='prompt-textarea']",
        "textarea[id='prompt-textarea']",
        "div[contenteditable='true'][role='textbox']",
        "div[contenteditable='true']",
        "textarea[data-id='root']",
        "textarea[placeholder*='Ask']",
        "textarea[placeholder*='Message']",
    )

    # File / image upload attachment button & hidden input
    file_inputs: List[str] = (
        "input[type='file']",
        "input[type='file'][tabindex='-1']",
    )

    attach_buttons: List[str] = (
        "button[aria-label*='Attach']",
        "button[aria-label*='Upload']",
        "button[data-testid='attach-button']",
        "button[aria-label*='Add files']",
    )

    # Send / Submit message button
    send_buttons: List[str] = (
        "button[data-testid='send-button']",
        "button[data-testid='fruitjuice-send-button']",
        "button[aria-label*='Send prompt']",
        "button[aria-label*='Send message']",
        "button[aria-label*='Send']",
    )

    # Stop generation button (visible while ChatGPT is thinking / generating)
    stop_buttons: List[str] = (
        "button[data-testid='stop-button']",
        "button[aria-label*='Stop generating']",
        "button[aria-label*='Stop']",
    )

    # Assistant messages & rendered images
    assistant_messages: List[str] = (
        "[data-message-author-role='assistant']",
        "div[data-message-author-role='assistant']",
        "article[data-testid^='conversation-turn']",
    )

    generated_images: List[str] = (
        "img[alt*='Generated by DALL']",
        "img[alt*='Generated image']",
        "img[alt*='Image']",
        "div[data-message-author-role='assistant'] img",
        "article img",
    )

    # Download controls
    download_buttons: List[str] = (
        "button[aria-label*='Download']",
        "button[aria-label*='download']",
        "button[data-testid*='download']",
        "a[download]",
        "button:has-text('Download')",
    )

    # Login / Authentication indicators
    login_buttons: List[str] = (
        "button[data-testid='login-button']",
        "a[href*='/auth/login']",
        'button:has-text("Log in")',
        'button:has-text("Sign up")',
    )

    # User profile / Logged-in indicators
    user_indicators: List[str] = (
        "button[data-testid='profile-button']",
        "button[aria-label*='Open user menu']",
        "button[aria-label*='User menu']",
        "div[data-testid='user-menu-trigger']",
        "#prompt-textarea",
    )

    # Error banners or modal warnings
    error_banners: List[str] = (
        "div[role='alert']",
        ".text-red-500",
        "[data-testid='error-notification']",
        'div:has-text("Something went wrong")',
        'div:has-text("reached our limit")',
        'div:has-text("Too many requests")',
    )


selectors = ChatGPTSelectors()
